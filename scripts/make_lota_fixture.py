"""Write explicitly synthetic LOTA-style ZIPs (Nerfstudio + Depth, COLMAP, PLY) for testing the importer.

The layout follows LOTA's documented exports; real exports may differ in details. Each ZIP
carries SYNTHETIC_TEST_CAPTURE.txt so the dashboard never shows it as a real scan.
"""
from pathlib import Path
import io, json, struct, sys, zipfile
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np
from PIL import Image
from backend.capture import quaternion

ROOT = Path(__file__).resolve().parents[1]
W, H, F = 160, 120, 140.0
FRAMES = 24
SPIKE = 10  # This frame jumps 0.8 m sideways and back: a simulated rover jolt.
MARKER = ('SYNTHETIC_TEST_CAPTURE.txt', 'Generated by scripts/make_lota_fixture.py. Not a real scan.\n')


def room(n=60000, seed=0):
    """Floor, three walls and a box (Y-up, metres), plus a few isolated floaters."""
    rng = np.random.default_rng(seed); parts = []
    def surface(count, fn, colour):
        u, v = rng.random(count), rng.random(count)
        parts.append((fn(u, v), np.tile(colour, (count, 1))))
    surface(n // 2, lambda u, v: np.c_[u*4 - 2, np.zeros_like(u), v*4 - 3], (120, 110, 95))
    surface(n // 6, lambda u, v: np.c_[u*4 - 2, v*2.5, np.full_like(u, -3)], (170, 180, 190))
    surface(n // 6, lambda u, v: np.c_[np.full_like(u, -2), v*2.5, u*4 - 3], (190, 175, 160))
    surface(n // 6, lambda u, v: np.c_[np.full_like(u, 2), v*2.5, u*4 - 3], (190, 175, 160))
    surface(n // 12, lambda u, v: np.c_[u*.6 + .4, v*.6, np.full_like(u, -1.8)], (210, 120, 50))
    xyz = np.concatenate([p for p, _ in parts]); rgb = np.concatenate([c for _, c in parts]).astype(np.uint8)
    floaters = rng.random((40, 3)) * [4, 2.5, 4] - [2, 0, 3] + rng.normal(0, .02, (40, 3))
    xyz = np.concatenate([xyz, floaters]); rgb = np.concatenate([rgb, np.full((40, 3), 255, np.uint8)])
    return xyz, rgb


def poses():
    """Camera-to-world (OpenGL: -z forward) for a rover driving forward while turning slowly."""
    out = []
    for i in range(FRAMES):
        yaw = np.radians(-20 + 40 * i / (FRAMES - 1)); c, s = np.cos(yaw), np.sin(yaw)
        T = np.eye(4); T[:3, :3] = [[c, 0, s], [0, 1, 0], [-s, 0, c]]
        T[:3, 3] = [0.8 if i == SPIKE else 0.0, 0.3, 0.5 - 2.0 * i / (FRAMES - 1)]
        out.append(T)
    return out


def jpeg(i):
    v, u = np.mgrid[:H, :W]
    rgb = np.stack([80 + u // 2, 90 + v, np.full_like(u, 60 + 6 * i)], axis=2).clip(0, 255).astype(np.uint8)
    buf = io.BytesIO(); Image.fromarray(rgb).save(buf, 'JPEG'); return buf.getvalue()


def ply_bytes(xyz, rgb, ascii=False):
    header = (f'ply\nformat {"ascii" if ascii else "binary_little_endian"} 1.0\nelement vertex {len(xyz)}\n'
              'property float x\nproperty float y\nproperty float z\n'
              'property uchar red\nproperty uchar green\nproperty uchar blue\nend_header\n').encode()
    if ascii:
        return header + ''.join(f'{x:.5f} {y:.5f} {z:.5f} {r} {g} {b}\n'
                                for (x, y, z), (r, g, b) in zip(xyz, rgb)).encode()
    v = np.empty(len(xyz), dtype=[('p', '<f4', 3), ('c', 'u1', 3)]); v['p'] = xyz; v['c'] = rgb
    return header + v.tobytes()


def nerfstudio(path, depth=True, folder='LOTA_scene/', ascii_ply=False):
    xyz, rgb = room()
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr(folder + MARKER[0], MARKER[1])
        frames = []
        for i, T in enumerate(poses(), 1):
            name = f'frame_{i:05d}'
            z.writestr(f'{folder}images/{name}.jpg', jpeg(i))
            frame = {'file_path': f'images/{name}.jpg', 'transform_matrix': T.tolist()}
            if depth:
                buf = io.BytesIO(); Image.fromarray(np.full((H // 2, W // 2), 2000, np.uint16)).save(buf, 'PNG')
                z.writestr(f'{folder}depth/{name}.png', buf.getvalue()); frame['depth_file_path'] = f'depth/{name}.png'
            frames.append(frame)
        meta = {'camera_model': 'OPENCV', 'fl_x': F, 'fl_y': F, 'cx': W / 2, 'cy': H / 2, 'w': W, 'h': H,
                'ply_file_path': 'points3D.ply', 'frames': frames}
        z.writestr(folder + 'transforms.json', json.dumps(meta, indent=2))
        z.writestr(folder + 'points3D.ply', ply_bytes(xyz, rgb, ascii_ply))


def colmap(path):
    xyz, rgb = room()
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr(MARKER[0], MARKER[1])
        z.writestr('cameras.bin', struct.pack('<QiiQQ4d', 1, 1, 1, W, H, F, F, W / 2, H / 2))
        records = []
        for i, T in enumerate(poses(), 1):
            name = f'frame_{i:05d}.jpg'; z.writestr(f'images/{name}', jpeg(i))
            R_w2c = (T[:3, :3] @ np.diag([1., -1., -1.])).T  # OpenGL -> OpenCV camera, then invert.
            t = -R_w2c @ T[:3, 3]
            records.append(struct.pack('<i4d3di', i, *quaternion(R_w2c), *t, 1) + name.encode() + b'\0' + struct.pack('<Q', 0))
        z.writestr('images.bin', struct.pack('<Q', len(records)) + b''.join(records))
        pts = np.zeros(len(xyz), dtype=[('id', '<u8'), ('xyz', '<f8', 3), ('rgb', 'u1', 3), ('err', '<f8'), ('track', '<u8')])
        pts['id'] = np.arange(1, len(xyz) + 1); pts['xyz'] = xyz; pts['rgb'] = rgb
        z.writestr('points3D.bin', struct.pack('<Q', len(xyz)) + pts.tobytes())


def ply_only(path):
    xyz, rgb = room()
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr(MARKER[0], MARKER[1]); z.writestr('points3D.ply', ply_bytes(xyz, rgb))


if __name__ == '__main__':
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'data' / 'lota_fixtures'
    out.mkdir(parents=True, exist_ok=True)
    nerfstudio(out / 'LOTA_SYNTHETIC_NERFSTUDIO_DEPTH.zip')
    colmap(out / 'LOTA_SYNTHETIC_COLMAP.zip')
    ply_only(out / 'LOTA_SYNTHETIC_PLY.zip')
    print('Wrote SYNTHETIC LOTA-style ZIPs to', out)
